def progress_bar(label, value, maximum, colour):

    width = 260
    height = 18

    drawing = Drawing(width + 120, 32)

    # Label

    drawing.add(
        String(
            0,
            22,
            label,
            fontName=FONT_BOLD,
            fontSize=10,
            fillColor=WHITE,
        )
    )

    # Background Bar

    drawing.add(
        Rect(
            85,
            12,
            width,
            height,
            fillColor=CARD_ALT,
            strokeColor=GREY,
            strokeWidth=0.5,
        )
    )

    # Filled Bar

    if maximum > 0:
        fill_width = (value / maximum) * width
    else:
        fill_width = 0

    drawing.add(
        Rect(
            85,
            12,
            fill_width,
            height,
            fillColor=colour,
            strokeColor=None,
        )
    )

    # Value

    drawing.add(
        String(
            width + 95,
            22,
            str(value),
            fontName=FONT_BOLD,
            fontSize=10,
            fillColor=WHITE,
        )
    )

    return drawing

