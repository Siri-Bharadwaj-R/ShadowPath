def risk_gauge(score, posture):

    score = max(0, min(score, 100))

    drawing = Drawing(205, 205)

    if score >= 75:
        colour = GREEN
    elif score >= 50:
        colour = BLUE
    elif score >= 25:
        colour = ORANGE
    else:
        colour = RED

    # Background Ring

    drawing.add(
        Circle(
            102,
            102,
            70,
            strokeColor=GREY,
            strokeWidth=12,
            fillColor=None,
        )
    )

    # Progress Arc

    angle = (score / 100.0) * 360

    drawing.add(
        Wedge(
            102,
            102,
            70,
            90,
            90 - angle,
            strokeColor=colour,
            strokeWidth=12,
            fillColor=None,
        )
    )

    # Inner Circle

    drawing.add(
        Circle(
            102,
            102,
            56,
            fillColor=BACKGROUND,
            strokeColor=None,
        )
    )

    # Score

    drawing.add(
        String(
            102,
            126,
            str(score),
            textAnchor="middle",
            fontName=FONT_BOLD,
            fontSize=32,
            fillColor=WHITE,
        )
    )

    drawing.add(
        String(
            102,
            101,
            "/100",
            textAnchor="middle",
            fontName=FONT,
            fontSize=12,
            fillColor=LIGHT,
        )
    )

    drawing.add(
        String(
            102,
            74,
            posture.upper(),
            textAnchor="middle",
            fontName=FONT_BOLD,
            fontSize=14,
            fillColor=colour,
        )
    )

    drawing.add(
        String(
            102,
            38,
            "Overall Security Score",
            textAnchor="middle",
            fontName=FONT,
            fontSize=10,
            fillColor=LIGHT,
        )
    )

    return drawing


